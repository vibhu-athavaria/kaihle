"""DeepEval-free judge configuration and independence guards (MLH-T18 slice 4).

Pure functions: the judge model and the task -> model map are PARAMETERS, never read from
globals, so production code (which cannot import ``evals.judge``: it needs DeepEval) and the
offline harness share one rule set. ``evals.judge`` delegates its task checks here.

Two independence questions, deliberately different:
  * Offline (``task_problem``): the graded task's CURRENT model must differ from the judge; a shared
    vendor is only a warning because the harness can still run.
  * Production (``row_independence``): each sampled row is checked against the model that
    GENERATED THAT ROW (``llm_usage_events.model``, possibly a model since replaced). A row from the
    judge's model OR vendor is skipped - stricter, because here the row can simply be excluded.

The vendor comparison is a HEURISTIC on the leading path segment of the model string; aggregators,
self-hosted endpoints and bare model names can hide or fake a shared vendor.
"""

from collections.abc import Mapping
from enum import StrEnum

from app.ai.eval.judge_config import JudgeConfigError, JudgeNotConfiguredError, JudgeNotIndependentError

JUDGE_UNSET_MESSAGE = "LLM_EVAL_JUDGE_MODEL is not set; the eval harness cannot run without a judge."
_OPENROUTER_PREFIX = "openrouter/"

TaskProblem = tuple[type[RuntimeError], str]


class RowIndependence(StrEnum):
    INDEPENDENT = "independent"
    SAME_MODEL = "same_model"
    SAME_VENDOR = "same_vendor"
    UNKNOWN = "unknown"  # the row records no model, so independence cannot be verified


def vendor_token(model: str) -> str | None:
    """First path segment after an optional ``openrouter/`` prefix, lowercased; None if there is no slash."""
    stripped = model.removeprefix(_OPENROUTER_PREFIX)
    if "/" not in stripped:
        return None
    return stripped.split("/", 1)[0].lower()


def require_judge_configured(judge_model: str) -> None:
    """Fail fast, naming the env var, when no judge model is configured."""
    if not judge_model:
        raise JudgeNotConfiguredError(JUDGE_UNSET_MESSAGE)


def row_independence(judge_model: str, row_model: str) -> RowIndependence:
    """Whether a row generated by ``row_model`` may be judged by ``judge_model`` (production rule)."""
    if not row_model.strip():
        return RowIndependence.UNKNOWN
    if row_model == judge_model:
        return RowIndependence.SAME_MODEL
    judge_vendor = vendor_token(judge_model)
    if judge_vendor is not None and judge_vendor == vendor_token(row_model):
        return RowIndependence.SAME_VENDOR
    return RowIndependence.INDEPENDENT


def task_problem(task: str, *, judge_model: str, task_model_map: Mapping[str, str]) -> TaskProblem | None:
    """Problem with the graded task alone (unknown, no model, or identical to the judge)."""
    if task not in task_model_map:
        return JudgeConfigError, f"Unknown graded task {task!r}; valid tasks: {sorted(task_model_map)}."
    graded_model = task_model_map[task]
    if not graded_model:
        return JudgeConfigError, f"No model is configured for graded task {task!r}; independence cannot be checked."
    if judge_model == graded_model:
        return (
            JudgeNotIndependentError,
            f"Judge model is identical to the model under test for task {task!r}; "
            "set LLM_EVAL_JUDGE_MODEL to a different model.",
        )
    return None


def config_problem(task: str, *, judge_model: str, task_model_map: Mapping[str, str]) -> TaskProblem | None:
    """Judge unset, else the task problem."""
    if not judge_model:
        return JudgeNotConfiguredError, JUDGE_UNSET_MESSAGE
    return task_problem(task, judge_model=judge_model, task_model_map=task_model_map)
